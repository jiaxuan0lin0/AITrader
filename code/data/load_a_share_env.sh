#!/usr/bin/env bash
# Source this file from shell scripts before reading AITrader path variables.

if [[ -n "${ROOT_DIR:-}" ]]; then
  AITRADER_CODE_ROOT="${AITRADER_CODE_ROOT:-$ROOT_DIR}"
else
  AITRADER_CODE_ROOT="${AITRADER_CODE_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
fi

AITRADER_ROOT="${AITRADER_ROOT:-$(cd "$AITRADER_CODE_ROOT/.." && pwd)}"
AITRADER_DATA_ROOT="${AITRADER_DATA_ROOT:-$AITRADER_ROOT/data}"
A_SHARE_ENV_FILE_DEFAULT="${A_SHARE_ENV_FILE_DEFAULT:-${AITRADER_SECRETS_DIR:-$AITRADER_DATA_ROOT/secrets}/a_share_pipeline.env}"

if [[ -n "${ROOT_DIR:-}" ]]; then
  A_SHARE_LOCAL_ENV_FILE_DEFAULT="$ROOT_DIR/data/secrets/a_share_pipeline.env"
else
  A_SHARE_LOCAL_ENV_FILE_DEFAULT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/data/secrets/a_share_pipeline.env"
fi

A_SHARE_LOCAL_ENV_FILE="${A_SHARE_LOCAL_ENV_FILE:-$A_SHARE_LOCAL_ENV_FILE_DEFAULT}"

if [[ -z "${A_SHARE_ENV_FILE:-}" ]]; then
  if [[ -f "$A_SHARE_ENV_FILE_DEFAULT" ]]; then
    A_SHARE_ENV_FILE="$A_SHARE_ENV_FILE_DEFAULT"
  else
    A_SHARE_ENV_FILE="$A_SHARE_LOCAL_ENV_FILE"
  fi
fi

if [[ -f "$A_SHARE_ENV_FILE" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$A_SHARE_ENV_FILE"
  set +a
fi

AITRADER_ROOT="${AITRADER_ROOT:-$(cd "$AITRADER_CODE_ROOT/.." && pwd)}"
AITRADER_DATA_ROOT="${AITRADER_DATA_ROOT:-$AITRADER_ROOT/data}"
AITRADER_RAW_DATA_DIR="${AITRADER_RAW_DATA_DIR:-$AITRADER_DATA_ROOT/raw_market_data}"
AITRADER_DATASETS_ROOT="${AITRADER_DATASETS_ROOT:-$AITRADER_DATA_ROOT/datasets}"
AITRADER_EXPERIMENTS_ROOT="${AITRADER_EXPERIMENTS_ROOT:-$AITRADER_DATA_ROOT/experiments}"
AITRADER_MODELS_ROOT="${AITRADER_MODELS_ROOT:-$AITRADER_DATA_ROOT/models}"
AITRADER_LOG_DIR="${AITRADER_LOG_DIR:-$AITRADER_DATA_ROOT/logs}"
AITRADER_RUNTIME_DIR="${AITRADER_RUNTIME_DIR:-$AITRADER_DATA_ROOT/runtime}"
AITRADER_SECRETS_DIR="${AITRADER_SECRETS_DIR:-$AITRADER_DATA_ROOT/secrets}"
AITRADER_PYTHON_BIN="${AITRADER_PYTHON_BIN:-${PYTHON_BIN:-python3}}"

export AITRADER_CODE_ROOT AITRADER_ROOT AITRADER_DATA_ROOT AITRADER_RAW_DATA_DIR
export AITRADER_DATASETS_ROOT AITRADER_EXPERIMENTS_ROOT AITRADER_MODELS_ROOT AITRADER_LOG_DIR
export AITRADER_RUNTIME_DIR AITRADER_SECRETS_DIR AITRADER_PYTHON_BIN
